// VARIABEL GAME

let selectedLevel = "";
let selectedTime = 0;
let totalQuestions = 5;

let gameQuestions = [];
let currentQuestion = 0;

let score = 0;
let correct = 0;
let wrong = 0;

let timerInterval;

// PILIH LEVEL

function selectLevel(level) {

    selectedLevel = level;

    document.getElementById("homePage").classList.add("hidden");
    document.getElementById("settingPage").classList.remove("hidden");

    const title = document.getElementById("settingTitle");

    const mediumSetting =
        document.getElementById("mediumSetting");

    const customSetting =
        document.getElementById("customSetting");


    mediumSetting.classList.add("hidden");
    customSetting.classList.add("hidden");


    if (level === "easy") {

        title.textContent = "Easy";

    }

    else if (level === "medium") {

        title.textContent = "Medium";

        mediumSetting.classList.remove("hidden");

    }

    else if (level === "custom") {

        title.textContent = "Custom";

        customSetting.classList.remove("hidden");

    }
}

// MULAI GAME


function startGame() {

    clearInterval(timerInterval);

    // EASY
    if (selectedLevel === "easy") {

        totalQuestions = questions.length;
        selectedTime = 0;

    }


    // MEDIUM
    else if (selectedLevel === "medium") {

        selectedTime =
            Number(document.getElementById("mediumTime").value);

        totalQuestions = questions.length;

    }


    // CUSTOM
    else if (selectedLevel === "custom") {

        selectedTime =
            Number(document.getElementById("customTime").value);

        totalQuestions =
            Number(document.getElementById("questionCount").value);


        // Kalau jumlah soal lebih banyak
        // daripada jumlah soal yang tersedia
        if (totalQuestions > questions.length) {

            totalQuestions = questions.length;

        }

    }


    // Acak soal
    gameQuestions = shuffleArray(questions)
        .slice(0, totalQuestions);


    currentQuestion = 0;
    score = 0;
    correct = 0;
    wrong = 0;


    document.getElementById("settingPage")
        .classList.add("hidden");

    document.getElementById("gamePage")
        .classList.remove("hidden");


    updateScore();

    showQuestion();
}


// RANDOM SOAL

function shuffleArray(array) {

    const newArray = [...array];

    for (
        let i = newArray.length - 1;
        i > 0;
        i--
    ) {

        const randomIndex =
            Math.floor(Math.random() * (i + 1));

        [
            newArray[i],
            newArray[randomIndex]
        ] =
        [
            newArray[randomIndex],
            newArray[i]
        ];
    }

    return newArray;
}


// TAMPILKAN SOAL

function showQuestion() {

    clearInterval(timerInterval);

    const question =
        gameQuestions[currentQuestion];


    document.getElementById("questionNumber")
        .textContent =
        `Soal ${currentQuestion + 1} / ${totalQuestions}`;


    document.getElementById("questionImage")
        .src = question.image;


    document.getElementById("answerInput")
        .value = "";


    document.getElementById("answerInput")
        .disabled = false;


    document.querySelector(".answer-button")
        .disabled = false;


    document.getElementById("feedback")
        .classList.add("hidden");


    document.getElementById("nextButton")
        .classList.add("hidden");

    document.getElementById("finishButton")
        .classList.remove("hidden");


    // EASY
    if (selectedLevel === "easy") {

        document.getElementById("timerContainer")
            .classList.add("hidden");

        document.getElementById("questionImage")
            .style.visibility = "visible";

    }


    // MEDIUM / CUSTOM
    else {

        document.getElementById("timerContainer")
            .classList.remove("hidden");

        document.getElementById("questionImage")
            .style.visibility = "visible";

        startImageTimer();

    }
}



// TIMER GAMBAR

function startImageTimer() {

    let remainingTime = selectedTime;

    const timer =
        document.getElementById("timer");

    timer.textContent = remainingTime;


    timerInterval = setInterval(() => {

        remainingTime--;

        timer.textContent = remainingTime;


        if (remainingTime <= 0) {

            clearInterval(timerInterval);

            // Gambar menghilang
            document.getElementById("questionImage")
                .style.visibility = "hidden";

        }

    }, 1000);
}


// CEK JAWABAN
function checkAnswer() {

    const input =
        document.getElementById("answerInput");

    const userAnswer =
        Number(input.value);

    if (input.value.trim() === "") {

        alert("Silakan masukkan jawaban.");

        return;
    }

    const correctAnswer =
        gameQuestions[currentQuestion].answer;

    // Supaya tidak bisa menjawab dua kali
    input.disabled = true;

    document.querySelector(".answer-button")
        .disabled = true;


  
    // CEK JAWABAN
    if (userAnswer === correctAnswer) {

        correct++;

        score += 100;

        showFeedback(
            `✅ BENAR! Jawabannya ${correctAnswer}`,
            true
        );

    } else {

        wrong++;

        showFeedback(
            `❌ SALAH! Jawaban yang benar: ${correctAnswer}`,
            false
        );

    }

    updateScore();


    // =========================
    // EASY
    // =========================

    if (selectedLevel === "easy") {

        // Easy tetap manual
        // User harus klik Lanjut

        document.getElementById("nextButton")
            .classList.remove("hidden");

        return;
    }


    // =========================
    // MEDIUM & CUSTOM
    // =========================

    if (
        selectedLevel === "medium" ||
        selectedLevel === "custom"
    ) {

        // Tunggu 1 detik kemudian
        // otomatis lanjut

        setTimeout(() => {

            nextQuestion();

        }, 1000);

    }

}


// FEEDBACK


function showFeedback(message, isCorrect) {

    const feedback =
        document.getElementById("feedback");

    feedback.textContent = message;

    feedback.classList.remove("hidden");

}



// SOAL BERIKUTNYA


function nextQuestion() {

    currentQuestion++;


    if (currentQuestion >= totalQuestions) {

        showResult();

        return;

    }


    showQuestion();
}

function finishGame() {

    clearInterval(timerInterval);

    showResult();

}

// SCORE
function updateScore() {

    document.getElementById("score")
        .textContent =
        `⭐ ${score}`;

}

// HASIL
function showResult() {

    clearInterval(timerInterval);

    document.getElementById("gamePage")
        .classList.add("hidden");

    document.getElementById("resultPage")
        .classList.remove("hidden");


    document.getElementById("finalScore")
        .textContent = score;

    document.getElementById("correctCount")
        .textContent = correct;

    document.getElementById("wrongCount")
        .textContent = wrong;


    const accuracy =
        totalQuestions === 0
            ? 0
            : Math.round(
                (correct / totalQuestions) * 100
            );


    document.getElementById("accuracy")
        .textContent = `${accuracy}%`;
}


// MAIN LAGI

function restartGame() {

    document.getElementById("resultPage")
        .classList.add("hidden");

    document.getElementById("gamePage")
        .classList.remove("hidden");

    startGame();
}


// KEMBALI KE HOME
function goHome() {

    clearInterval(timerInterval);

    document.getElementById("settingPage")
        .classList.add("hidden");

    document.getElementById("gamePage")
        .classList.add("hidden");

    document.getElementById("resultPage")
        .classList.add("hidden");

    document.getElementById("homePage")
        .classList.remove("hidden");
}

// ENTER = JAWAB
document.getElementById("answerInput")
    .addEventListener("keydown", function(event) {

        if (event.key === "Enter") {

            checkAnswer();

        }

    });

